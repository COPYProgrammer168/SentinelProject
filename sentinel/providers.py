def is_ip_in_trusted_range(ip: str) -> Optional[str]:
    """Check if an IP address falls within any trusted provider CIDR range.

    Returns the provider name if found, None otherwise.
    """
    if not ip:
        return None
    try:
        ip_obj = ipaddress.ip_address(ip)
    except ValueError:
        return None

    for provider, cidr_list in get_trusted_provider_cidrs().items():
        for cidr_str in cidr_list:
            try:
                network = ipaddress.ip_network(cidr_str, strict=False)
                if ip_obj in network:
                    return provider
            except ValueError:
                continue
    return None


def refresh_provider_cidrs(force: bool = False) -> Dict[str, List[str]]:
    """Refresh provider CIDR lists from official sources.

    Fetches from provider JSON endpoints and updates the local cache.
    Only refreshes if force=True or if the cache is older than 24 hours.

    Returns the current CIDR dictionary.
    """
    cache_key = "provider_cidrs_last_refresh"
    from sentinel.db.storage import Storage
    import os
    import tempfile

    storage = Storage(os.path.join(tempfile.gettempdir(), "sentinel_provider_cache.db"))
    last_refresh = storage.get_meta(cache_key)

    if not force and last_refresh:
        try:
            from datetime import datetime, timezone, timedelta
            last_dt = datetime.fromisoformat(last_refresh)
            if (datetime.now(timezone.utc) - last_dt) < timedelta(hours=24):
                return get_trusted_provider_cidrs()
        except Exception:
            pass

    for provider, url in PROVIDER_JSON_URLS.items():
        try:
            req = urlopen(url, timeout=10)
            data = json.loads(req.read().decode("utf-8"))
            new_cidrs = []
            if provider == "Google" and "prefixes" in data:
                for entry in data["prefixes"]:
                    if "ipv4_prefix" in entry:
                        new_cidrs.append(entry["ipv4_prefix"])
            elif provider == "AWS" and "prefixes" in data:
                for entry in data["prefixes"]:
                    if "ip_prefix" in entry:
                        new_cidrs.append(entry["ip_prefix"])
            elif provider == "Microsoft/Azure":
                pass
            if new_cidrs:
                BUILTIN_CIDRS[provider] = new_cidrs
        except Exception:
            pass

    storage.set_meta(cache_key, datetime.now(timezone.utc).isoformat())
    return get_trusted_provider_cidrs()
